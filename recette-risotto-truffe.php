<section class="col-md-6">
    <h2>Ingrédients</h2>
    <ul>
        <li>300 g de riz Arborio</li>
        <li>20 g de truffe noire</li>
        <li>1 litre de bouillon de légumes</li>
        <li>1 oignon</li>
        <li>50 g de parmesan</li>
        <li>30 g de beurre</li>
        <li>2 cuillères à soupe d'huile d'olive</li>
        <li>Sel et poivre</li>
    </ul>
</section>

<section class="col-md-6">
    <h2>Ustensiles</h2>

    <ul>
        <li>Une casserole</li>
        <li>Une poêle profonde</li>
        <li>Une cuillère en bois</li>
        <li>Un couteau</li>
        <li>Une râpe</li>
    </ul>
</section>
</div>

<section>
    <h2>Préparation</h2>

    <ol>
        <li>Faire chauffer le bouillon dans une casserole.</li>
        <li>Éplucher et couper finement l'oignon.</li>
        <li>Faire revenir l'oignon dans l'huile d'olive.</li>
        <li>Ajouter le riz et mélanger pendant 2 minutes.</li>
        <li>Ajouter le bouillon progressivement en remuant.</li>
        <li>Laisser cuire environ 18 à 20 minutes.</li>
        <li>Ajouter le beurre et le parmesan.</li>
        <li>Râper la truffe sur le risotto et servir.</li>
    </ol>
</section>
